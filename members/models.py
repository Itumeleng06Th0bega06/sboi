"""Church membership records.

These models are an *extension* of the existing authentication system. They
do not replace ``blackboard.MemberProfile`` (which controls access to the
members portal) or Django's ``User``. A ``ChurchMembership`` is an optional
profile linked one-to-one to an authenticated account, so a visitor can
register as a normal website user, or (later) attach church membership
details without creating a second account.

Nothing beyond what the existing authentication system needs (a username,
email address and password) is required. Every personal-profile and
church-specific question is optional, so members can register with minimal
information and complete their profile later. All optional fields use
``blank=True`` (and ``null=True`` for dates) so blank values always save.
"""

