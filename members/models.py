# Models
# ---------------------------------------------------------------------------

class ChurchMembership(models.Model):
    """A church member / participant profile linked to a user account."""

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='church_membership',
    )
    # Generated by the backend after insert (see save()). NULL keeps the
    # unique column safe while several rows are being created concurrently.
    membership_id = models.CharField(
        max_length=32, unique=True, null=True, blank=True, editable=False,
    )

    # --- Section A: personal details (name/email live on the User) --------
    phone = models.CharField('Phone number', max_length=30, blank=True)
    alt_phone = models.CharField('Alternative phone number', max_length=30, blank=True)
    date_of_birth = models.DateField(null=True, blank=True)
    gender = models.CharField(max_length=12, choices=GENDER_CHOICES, blank=True)
    address = models.CharField('Residential address', max_length=255, blank=True)
    city = models.CharField('Suburb or town', max_length=120, blank=True)
    province = models.CharField('Province', max_length=120, blank=True)
    emergency_contact_name = models.CharField(max_length=120, blank=True)
    emergency_contact_phone = models.CharField(max_length=30, blank=True)

    # --- Family -----------------------------------------------------------
    marital_status = models.CharField(
        'Marital status', max_length=12, choices=MARITAL_STATUS_CHOICES,
        blank=True,
    )
    spouse_name = models.CharField('Spouse full name', max_length=200, blank=True)
    children_names = models.TextField(
        'Children', blank=True,
        help_text=(
            'One child per line. Children aged 16 and over can create their '
            'own membership form.'
        ),
    )

    # --- Section B: church membership information -------------------------
    membership_category = models.CharField(
        max_length=20, choices=MEMBERSHIP_CATEGORY_CHOICES, blank=True,
    )
    status = models.CharField(
        max_length=12, choices=MEMBERSHIP_STATUS_CHOICES, default='active',
    )
    date_joined_church = models.DateField(null=True, blank=True)
    baptism_status = models.CharField(
        max_length=14, choices=BAPTISM_STATUS_CHOICES, blank=True,
    )
    baptism_date = models.DateField(null=True, blank=True)
    previous_church = models.CharField(max_length=200, blank=True)
    transferring_from_church = models.BooleanField(default=False)
    preferred_language = models.CharField(max_length=60, blank=True)
    campus_branch = models.CharField(max_length=120, blank=True)

    # --- Section C: interests and spiritual growth ------------------------
    interests_other = models.CharField(max_length=200, blank=True)
    spiritual_growth_goals = models.TextField(blank=True)
    wants_bible_study = models.BooleanField(default=False)
    wants_contact = models.BooleanField(default=False)

    # --- Section D: current church activities -----------------------------
    currently_involved = models.BooleanField(default=False)
    current_activities = models.TextField(
        'Current ministries / activities', blank=True,
    )
    small_group_name = models.CharField(max_length=200, blank=True)
    volunteers_currently = models.BooleanField(default=False)
    volunteer_details = models.TextField(blank=True)
    wants_to_volunteer = models.BooleanField(default=False)

    # --- Section E: skills, talents and availability ----------------------
    skills = models.TextField('Skills or professional experience', blank=True)
    talents = models.TextField(blank=True)
    service_areas = models.TextField(
        'Areas willing to serve in', blank=True,
    )
    preferred_times = models.CharField(
        'Preferred days or times', max_length=200, blank=True,
    )
    additional_info = models.TextField(blank=True)

    # --- Section F: additional information --------------------------------
    notes = models.TextField('Additional notes', blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = 'Church membership'
        verbose_name_plural = 'Church memberships'
        ordering = ['-created_at']
        permissions = [
            ('manage_membership', 'Membership: manage members'),
        ]

    def __str__(self):
        return f'{self.full_name} ({self.membership_id or "pending"})'

    def save(self, *args, **kwargs):
        super().save(*args, **kwargs)
        if not self.membership_id:
            new_id = f'SBOI-M-{self.pk:05d}'
            ChurchMembership.objects.filter(pk=self.pk).update(
                membership_id=new_id,
            )
            self.membership_id = new_id

    @property
    def full_name(self):
        return self.user.get_full_name() or self.user.get_username()

    @property
    def email(self):
        return self.user.email


class MembershipInterest(models.Model):
    """One row per interest selected in Section C."""

    membership = models.ForeignKey(
        ChurchMembership, on_delete=models.CASCADE, related_name='interests',
    )
    name = models.CharField(max_length=40, choices=INTEREST_CHOICES)

    class Meta:
        verbose_name = 'Membership interest'
        verbose_name_plural = 'Membership interests'
        unique_together = [('membership', 'name')]
        ordering = ['name']

    def __str__(self):
        return self.get_name_display()


class MembershipMinistry(models.Model):
    """A ministry/department the member is in, wants to join, or serves in."""

    membership = models.ForeignKey(
        ChurchMembership, on_delete=models.CASCADE, related_name='ministries',
    )
    name = models.CharField(max_length=40, choices=MINISTRY_CHOICES)
    status = models.CharField(
        max_length=12, choices=MINISTRY_STATUS_CHOICES, default='current',
    )

    class Meta:
        verbose_name = 'Membership ministry'
        verbose_name_plural = 'Membership ministries'
        unique_together = [('membership', 'name', 'status')]
        ordering = ['status', 'name']

    def __str__(self):
        return f'{self.get_name_display()} ({self.get_status_display()})'


class MembershipPastoralNote(models.Model):
    """Sensitive pastoral notes attached to a church membership.

    This model is deliberately not registered in the admin; pastoral notes are
    edited through the membership form. The membership area's single
    ``manage_membership`` permission covers the whole record.
    """

    membership = models.OneToOneField(
        ChurchMembership, on_delete=models.CASCADE, related_name='pastoral_note',
    )
    guidance_support = models.TextField(
        'Areas needing guidance or support', blank=True,
    )
    prayer_request = models.TextField(blank=True)
    pastoral_support_requested = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'Pastoral note'
        verbose_name_plural = 'Pastoral notes'

    def __str__(self):
        return f'Pastoral note for {self.membership}'

    @property
    def is_empty(self):
        return not (self.guidance_support or self.prayer_request
                    or self.pastoral_support_requested)
